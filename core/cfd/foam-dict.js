// OpenFOAM 字典（dictionary）的寫出與解析。純 JS，瀏覽器與 Node 都能用，不依賴 OpenFOAM。
//
// 寫出：用一般物件表示字典（鍵的順序就是輸出順序），值可以是
//   number → 數字（fmt 統一格式）；string → 原樣輸出的字（例如 'uniform (0 0 0)'、'"abc"'）；
//   boolean → true／false；陣列 → 小括號清單 ( … )；巢狀物件 → 子字典 { … }；
//   raw('…') → 原樣；dims([0 1 -1 0 0 0 0]) → [ … ]；list(…) → 可放 named() 子字典的清單（blockMesh 的 boundary）。
//   以 '#' 開頭的鍵是指令（#include、#includeEtc），不加分號；值為 null 的鍵略過。
// 解析：parseFoamDict(text) 轉成 { entries: [{ key, value, line }] }，value 是 { dict } 或 { tokens }；
//   語法錯誤（括號不成對、缺分號、未結束的字串或註解）丟出帶行號的 FoamSyntaxError。
//   這只是語法檢查，不展開 #include、$變數，也不知道各求解器要哪些鍵；語意檢查在 validate.js。

const RAW = Symbol('raw');
const LIST = Symbol('list');
const NAMED = Symbol('named');

export const raw = s => ({ [RAW]: String(s) });
export const dims = a => raw(`[${a.join(' ')}]`);
export const list = (...items) => ({ [LIST]: items });
export const named = (name, dict) => ({ [NAMED]: name, dict });
export const vec = a => raw(`(${a.map(fmt).join(' ')})`);
export const str = s => `"${s}"`;

// 數字統一格式：去掉浮點雜訊（10 位有效數字），極小值歸零，整數不加小數點。決定性。
export function fmt(n) {
  if (typeof n !== 'number' || !Number.isFinite(n)) throw new Error(`不是有限數字：${n}`);
  if (Math.abs(n) < 1e-12) return '0';
  const v = Number(n.toPrecision(10));
  return Object.is(v, -0) ? '0' : String(v);
}

const isPlainObject = v => v && typeof v === 'object' && !Array.isArray(v) && !(RAW in v) && !(LIST in v) && !(NAMED in v);

function valueText(v) {
  if (v === true) return 'true';
  if (v === false) return 'false';
  if (typeof v === 'number') return fmt(v);
  if (typeof v === 'string') return v;
  if (Array.isArray(v)) return `(${v.map(valueText).join(' ')})`;
  if (v && typeof v === 'object' && RAW in v) return v[RAW];
  throw new Error(`無法寫出的值：${JSON.stringify(v)}`);
}

const pad = (k, w = 16) => (k.length >= w ? `${k} ` : k.padEnd(w));

export function writeDict(obj, indent = 0) {
  const sp = ' '.repeat(indent);
  const out = [];
  for (const [k, v] of Object.entries(obj)) {
    if (v === null || v === undefined) continue;
    if (k.startsWith('#')) { out.push(`${sp}${k.replace(/~\d+$/, '')} ${valueText(v)}`); continue; }
    if (isPlainObject(v)) {
      out.push(`${sp}${k}`, `${sp}{`, ...writeDict(v, indent + 4), `${sp}}`);
    } else if (v && typeof v === 'object' && LIST in v) {
      out.push(`${sp}${k}`, `${sp}(`);
      for (const it of v[LIST]) {
        if (it && typeof it === 'object' && NAMED in it) out.push(`${sp}    ${it[NAMED]}`, `${sp}    {`, ...writeDict(it.dict, indent + 8), `${sp}    }`);
        else if (isPlainObject(it)) out.push(`${sp}    {`, ...writeDict(it, indent + 8), `${sp}    }`); // 匿名字典（topoSet 的 actions）
        else out.push(`${sp}    ${valueText(it)}`);
      }
      out.push(`${sp});`);
    } else {
      out.push(`${sp}${pad(k)}${valueText(v)};`);
    }
  }
  return out;
}

// 檔頭：FoamFile 子字典。不複製 OpenFOAM 的版權橫幅，只放本工具的說明。
export function foamFile({ cls = 'dictionary', object, location, note }, body) {
  const head = { version: '2.0', format: 'ascii', class: cls };
  if (location) head.location = str(location);
  head.object = object;
  const lines = [
    '/*---------------------------------------------------------------------------*\\',
    '  Generated by SimplePhysicsEngine cfd case generator (TEMP/cfd-dev).',
    note ? `  ${note}` : null,
    '  Edit the generator input JSON and regenerate instead of editing this file.',
    '\\*---------------------------------------------------------------------------*/',
    ...writeDict({ FoamFile: head }),
    '// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //',
    '',
    ...writeDict(body),
    '',
    '// ************************************************************************* //',
    '',
  ].filter(l => l !== null);
  return lines.join('\n');
}

// ---------------------------------------------------------------- 解析

export class FoamSyntaxError extends Error {
  constructor(msg, line) { super(line ? `第 ${line} 行：${msg}` : msg); this.line = line; }
}

export function tokenize(text) {
  const toks = [];
  let i = 0, line = 1;
  const n = text.length;
  while (i < n) {
    const c = text[i];
    if (c === '\n') { line++; i++; continue; }
    if (c === ' ' || c === '\t' || c === '\r') { i++; continue; }
    if (c === '/' && text[i + 1] === '/') { while (i < n && text[i] !== '\n') i++; continue; }
    if (c === '/' && text[i + 1] === '*') {
      const start = line; i += 2;
      while (i < n && !(text[i] === '*' && text[i + 1] === '/')) { if (text[i] === '\n') line++; i++; }
      if (i >= n) throw new FoamSyntaxError('區塊註解沒有結束', start);
      i += 2; continue;
    }
    if (c === '"') {
      const start = line; let j = i + 1;
      while (j < n && text[j] !== '"') { if (text[j] === '\\') j++; if (text[j] === '\n') line++; j++; }
      if (j >= n) throw new FoamSyntaxError('字串沒有結束', start);
      toks.push({ t: 'string', v: text.slice(i, j + 1), line: start }); i = j + 1; continue;
    }
    if ('{}()[];'.includes(c)) { toks.push({ t: c, v: c, line }); i++; continue; }
    // 字（word）：OpenFOAM 的字可以含 . : / - + * 等，以空白與標點結束；小括號在 word 中成對出現時算字的一部分（例如 div(phi,U)）
    let j = i, depth = 0;
    while (j < n) {
      const d = text[j];
      if (d === '(') { if (j === i) break; depth++; j++; continue; }
      if (d === ')') { if (depth === 0) break; depth--; j++; continue; }
      if (depth === 0 && (' \t\r\n{}[];"'.includes(d))) break;
      if (depth > 0 && d === '\n') break;
      j++;
    }
    if (j === i) throw new FoamSyntaxError(`無法辨識的字元 ${JSON.stringify(c)}`, line);
    const v = text.slice(i, j);
    const t = v[0] === '#' ? 'directive' : v[0] === '$' ? 'var' : /^[-+]?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?$/.test(v) ? 'number' : 'word';
    toks.push({ t, v, line }); i = j;
  }
  return toks;
}

export function parseFoamDict(text) {
  const toks = tokenize(text);
  let p = 0;
  const peek = () => toks[p];
  const lastLine = toks.length ? toks.at(-1).line : 1;

  // 讀一個值群組（小括號／中括號清單，可巢狀；清單中可有 名稱 { 字典 }）
  function readGroup(open) {
    const close = open === '(' ? ')' : ']';
    const start = toks[p - 1].line;
    const items = [];
    for (;;) {
      const t = toks[p++];
      if (!t) throw new FoamSyntaxError(`${open} 沒有對應的 ${close}`, start);
      if (t.t === close) return { group: open, items, line: start };
      if (t.t === '(' || t.t === '[') { items.push(readGroup(t.t)); continue; }
      if (t.t === '{') { items.push({ dict: readDictBody(t.line), line: t.line }); continue; }
      if (t.t === ')' || t.t === ']' || t.t === '}') throw new FoamSyntaxError(`多出的 ${t.t}（${open} 從第 ${start} 行開始）`, t.line);
      if (t.t === ';') throw new FoamSyntaxError(`${open} 清單裡出現分號（${open} 從第 ${start} 行開始，可能少了 ${close}）`, t.line);
      items.push(t);
    }
  }

  function readDictBody(openLine) {
    const entries = [];
    for (;;) {
      const t = peek();
      if (!t) {
        if (openLine === null) return entries;
        throw new FoamSyntaxError('{ 沒有對應的 }', openLine);
      }
      if (t.t === '}') {
        if (openLine === null) throw new FoamSyntaxError('多出的 }', t.line);
        p++; return entries;
      }
      if (t.t === ';') { p++; continue; } // 空敘述
      if (t.t === 'directive') {
        // 指令吃到行尾（#include "x"、#includeEtc "x"、#includeFunc name(args)、#remove …）
        p++;
        const args = [];
        while (peek() && peek().line === t.line && peek().t !== '}') args.push(toks[p++]);
        entries.push({ key: t.v, directive: true, args: args.map(a => a.v), line: t.line });
        continue;
      }
      if (t.t === 'var' && toks[p + 1]?.t === ';') { p += 2; entries.push({ key: t.v, macro: true, line: t.line }); continue; }
      if (!['word', 'string', 'number', 'var'].includes(t.t)) throw new FoamSyntaxError(`預期鍵名，卻是 ${t.v}`, t.line);
      p++;
      const key = t.v;
      if (peek()?.t === '{') { const o = toks[p++]; entries.push({ key, value: { dict: readDictBody(o.line) }, line: t.line }); continue; }
      // 值：到分號為止；群組完整讀入。清單後面直接接 } 或 EOF 時也報錯
      const tokens = [];
      for (;;) {
        const u = toks[p++];
        if (!u) throw new FoamSyntaxError(`鍵 ${key} 的值沒有以分號結束`, t.line);
        if (u.t === ';') break;
        if (u.t === '(' || u.t === '[') { tokens.push(readGroup(u.t)); continue; }
        if (u.t === '{' || u.t === '}' || u.t === ')' || u.t === ']') throw new FoamSyntaxError(`鍵 ${key} 的值裡出現 ${u.t}（可能少了分號）`, u.line);
        tokens.push(u);
      }
      entries.push({ key, value: { tokens }, line: t.line });
    }
  }

  const entries = readDictBody(null);
  return { entries, lastLine };
}

// 解析結果的小工具
export function entry(d, key) { return (d.entries || d).find(e => e.key === key); }
export function sub(d, ...path) {
  let cur = d;
  for (const k of path) { const e = entry(cur, k); if (!e || !e.value?.dict) return null; cur = { entries: e.value.dict }; }
  return cur;
}
export function keys(d) { return (d.entries || d).filter(e => !e.directive).map(e => e.key); }
// 把一個值轉回簡單的 JS：數字、字、巢狀陣列
export function plain(v) {
  if (!v) return v;
  if (v.tokens) return v.tokens.length === 1 ? plain(v.tokens[0]) : v.tokens.map(plain);
  if (v.group) return v.items.map(plain);
  if (v.dict) return { dict: v.dict };
  if (v.t === 'number') return Number(v.v);
  return v.v;
}
export function valueOf(d, ...path) {
  const k = path.pop();
  const s = path.length ? sub(d, ...path) : d;
  const e = s && entry(s, k);
  return e ? plain(e.value) : undefined;
}

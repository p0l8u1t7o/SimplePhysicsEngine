def style(ws, widths):
    for row in ws.iter_rows():
        for c in row:
            if c.font.color is None and not c.font.bold: c.font = BASE
            c.alignment = WRAP
    for k, w in enumerate(widths, start=1): ws.column_dimensions[get_column_letter(k)].width = w


def head(ws, row, n):
    for c in ws[row][:n]: c.font = BOLD; c.fill = FILL


